/** A 3x5 pixel font for text on the LCD. */
object PixelFont {
    const val WIDTH = 3
    const val HEIGHT = 5

    private val glyphs: Map<Char, PixelArt> = mapOf(
        'A' to g(".#.", "#.#", "###", "#.#", "#.#"),
        'B' to g("##.", "#.#", "##.", "#.#", "##."),
        'C' to g(".##", "#..", "#..", "#..", ".##"),
        'D' to g("##.", "#.#", "#.#", "#.#", "##."),
        'E' to g("###", "#..", "##.", "#..", "###"),
        'F' to g("###", "#..", "##.", "#..", "#.."),
        'G' to g(".##", "#..", "#.#", "#.#", ".##"),
        'H' to g("#.#", "#.#", "###", "#.#", "#.#"),
        'I' to g("###", ".#.", ".#.", ".#.", "###"),
        'J' to g("..#", "..#", "..#", "#.#", ".#."),
        'K' to g("#.#", "#.#", "##.", "#.#", "#.#"),
        'L' to g("#..", "#..", "#..", "#..", "###"),
        'M' to g("#.#", "###", "###", "#.#", "#.#"),
        'N' to g("##.", "#.#", "#.#", "#.#", "#.#"),
        'O' to g(".#.", "#.#", "#.#", "#.#", ".#."),
        'P' to g("##.", "#.#", "##.", "#..", "#.."),
        'Q' to g(".#.", "#.#", "#.#", "##.", ".##"),
        'R' to g("##.", "#.#", "##.", "#.#", "#.#"),
        'S' to g(".##", "#..", ".#.", "..#", "##."),
        'T' to g("###", ".#.", ".#.", ".#.", ".#."),
        'U' to g("#.#", "#.#", "#.#", "#.#", "###"),
        'V' to g("#.#", "#.#", "#.#", "#.#", ".#."),
        'W' to g("#.#", "#.#", "###", "###", "#.#"),
        'X' to g("#.#", "#.#", ".#.", "#.#", "#.#"),
        'Y' to g("#.#", "#.#", ".#.", ".#.", ".#."),
        'Z' to g("###", "..#", ".#.", "#..", "###"),
        '0' to g("###", "#.#", "#.#", "#.#", "###"),
        '1' to g(".#.", "##.", ".#.", ".#.", "###"),
        '2' to g("##.", "..#", ".#.", "#..", "###"),
        '3' to g("##.", "..#", ".#.", "..#", "##."),
        '4' to g("#.#", "#.#", "###", "..#", "..#"),
        '5' to g("###", "#..", "##.", "..#", "##."),
        '6' to g(".##", "#..", "###", "#.#", "###"),
        '7' to g("###", "..#", ".#.", ".#.", ".#."),
        '8' to g("###", "#.#", "###", "#.#", "###"),
        '9' to g("###", "#.#", "###", "..#", "##."),
        '!' to g(".#.", ".#.", ".#.", "...", ".#."),
        '?' to g("##.", "..#", ".#.", "...", ".#."),
        '-' to g("...", "...", "###", "...", "..."),
        ':' to g("...", ".#.", "...", ".#.", "..."),
        '/' to g("..#", "..#", ".#.", "#..", "#.."),
        '%' to g("#.#", "..#", ".#.", "#..", "#.#"),
        '.' to g("...", "...", "...", "...", ".#."),
        '+' to g("...", ".#.", "###", ".#.", "..."),
        ' ' to g("...", "...", "...", "...", "..."),
    )

    private fun g(vararg rows: String) = PixelArt.parse(*rows)

    fun glyph(c: Char): PixelArt = glyphs[c.uppercaseChar()] ?: glyphs.getValue('?')

    /** Width in pixels of [text] with one pixel between letters. */
    fun measure(text: String): Int = if (text.isEmpty()) 0 else text.length * (WIDTH + 1) - 1
}
