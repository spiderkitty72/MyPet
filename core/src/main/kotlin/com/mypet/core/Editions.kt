package com.mypet.core

enum class Stage(val label: String) {
    EGG("Egg"),
    BABY("Baby"),
    CHILD("Child"),
    TEEN("Teen"),
    ADULT("Adult"),
    SECRET("Secret"),
}

enum class GameKind(val title: String, val help: String) {
    WHICH_WAY("Which Way?", "Guess which way your pet will turn. Win 3 of 5."),
    HI_LO("Hi or Lo", "Will the next number be higher or lower? Win 3 of 5."),
    CATCH("Star Catch", "Tap STOP while the star is over the basket. Win 3 of 5."),
}

/**
 * One character in a growth line.
 *
 * @param lifespanDays only used for adult and secret forms: the age (in pet days)
 *   at which a pet in this form reaches the end of its life with perfect care.
 */
data class Form(
    val id: String,
    val name: String,
    val stage: Stage,
    val blurb: String,
    val sprite: PixelArt,
    val lifespanDays: Double = 0.0,
)

/**
 * Rule set for one "device edition". Every edition runs the same care loop with
 * slightly different numbers, the way different handheld versions over the years
 * felt different to raise.
 */
data class EditionRules(
    /** Game minutes for one hunger heart to drain while awake. */
    val hungerMinutes: Int,
    /** Game minutes for one happiness heart to drain while awake. */
    val happyMinutes: Int,
    /** Game minutes between droppings while awake. */
    val poopMinutes: Int,
    /** Base chance per awake game hour of catching a random bug. */
    val sicknessPerHour: Double,
    /** Chance per awake game hour of a "testing you" call that should be scolded. */
    val fakeCallPerHour: Double,
    /** Multiplies how long the child and teen stages last. */
    val stageScale: Double,
    /** Multiplies adult lifespans. */
    val lifespanScale: Double,
    /** Snacks within a short window that give the pet a tummy ache. */
    val snackLimit: Int,
    /** Bed and wake times as minutes after midnight on the pet's clock. */
    val bedtime: Int,
    val wakeTime: Int,
    /** Gentle editions end with the pet heading home instead of passing away. */
    val gentleEndings: Boolean,
    /** Happiness hearts for winning a game. */
    val gameReward: Int,
    val games: List<GameKind>,
)

data class Edition(
    val id: String,
    val name: String,
    val tagline: String,
    val description: String,
    /** Shell colour, LCD background and LCD ink as ARGB ints (kept platform-neutral). */
    val shellColor: Long,
    val shellAccent: Long,
    val lcdColor: Long,
    val inkColor: Long,
    val rules: EditionRules,
    val egg: Form,
    val baby: Form,
    val child: Form,
    val teenGood: Form,
    val teenBad: Form,
    val adultBest: Form,
    val adultOkay: Form,
    val adultRough: Form,
    val secret: Form,
) {
    val forms: List<Form>
        get() = listOf(egg, baby, child, teenGood, teenBad, adultBest, adultOkay, adultRough, secret)

    fun form(id: String): Form = forms.firstOrNull { it.id == id }
        ?: error("Unknown form $id in edition ${this.id}")
}

